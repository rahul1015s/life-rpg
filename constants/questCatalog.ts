function createQuestTemplate(input: {
  id: string;
  title: string;
  description: string;
  category: QuestCategory;
  difficulty: QuestDifficulty;
  baseXP: number;
  affectedStats: Partial<Record<StatKey, number>>;
  repeatType: 'daily' | 'weekly' | 'flexible';
  recommendedTime: string;
  whyThisHelps: string;
  safetyNote?: string;
}): QuestTemplate {
  return {
    ...input,
    safetyNote: input.safetyNote ?? null,
  };
}

